import { toBotMessage, verifyTelegramSecret } from './telegram.mjs';

const json = (value, status = 200) => new Response(JSON.stringify(value), {
  status, headers: {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
    'x-content-type-options': 'nosniff',
    'referrer-policy': 'no-referrer',
  },
});
const attemptDelayMs = (n) => Math.min(3_600_000, 5_000 * (2 ** Math.min(n, 9)));
const MAX_WEBHOOK_BYTES = 32_768;

async function parseBoundedJson(request) {
  const type = request.headers.get('content-type') ?? '';
  if (!/^application\/json(?:\s*;|\s*$)/i.test(type)) return { code: 415 };
  const declared = Number(request.headers.get('content-length'));
  if (Number.isFinite(declared) && declared > MAX_WEBHOOK_BYTES) return { code: 413 };
  const reader = request.body?.getReader();
  if (!reader) return { code: 400 };
  const chunks = [];
  let length = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      length += value.byteLength;
      if (length > MAX_WEBHOOK_BYTES) {
        await reader.cancel();
        return { code: 413 };
      }
      chunks.push(value);
    }
    const bytes = new Uint8Array(length);
    let offset = 0;
    for (const chunk of chunks) {
      bytes.set(chunk, offset);
      offset += chunk.byteLength;
    }
    const parsed = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return { code: 400 };
    return { value: parsed };
  } catch { return { code: 400 }; }
  finally { reader.releaseLock(); }
}

async function telegramApi(env, method, payload) {
  if (!env.BOT_TOKEN) return false;
  const response = await fetch('https://api.telegram.org/bot' + env.BOT_TOKEN + '/' + method, {
    method: 'POST', headers: { 'content-type': 'application/json' },
    body: JSON.stringify(payload), signal: AbortSignal.timeout(12_000),
  });
  return response.ok && (await response.json()).ok === true;
}

async function dispatchOutbox(env, nowMs = Date.now()) {
  if (!env.DB || !env.BOT_TOKEN) return;
  const results = await env.DB.prepare(
    "SELECT id, chat_id, body, reply_markup, attempts FROM telegram_outbox WHERE (state = 'pending' AND due_ms <= ?) OR (state = 'leased' AND lease_until_ms <= ?) ORDER BY id LIMIT 20"
  ).bind(nowMs, nowMs).all();
  for (const item of results.results ?? []) {
    const claim = await env.DB.prepare(
      "UPDATE telegram_outbox SET state='leased', lease_until_ms=?, attempts=attempts+1 WHERE id=? AND ((state='pending' AND due_ms<=?) OR (state='leased' AND lease_until_ms<=?))"
    ).bind(nowMs + 30_000, item.id, nowMs, nowMs).run();
    if (claim.meta?.changes !== 1) continue;
    let sent = false;
    try {
      // Reply markup is generated by our own trusted menu; never by a customer.
      const markup = item.reply_markup ? JSON.parse(item.reply_markup) : null;
      sent = await telegramApi(env, 'sendMessage', {
        chat_id: item.chat_id, text: item.body,
        ...(markup ? { reply_markup: markup } : {}),
      });
    } catch { /* transient network/Telegram error: retry, no sensitive logging */ }
    if (sent) {
      await env.DB.prepare("UPDATE telegram_outbox SET state='sent', lease_until_ms=0 WHERE id=? AND state='leased'")
        .bind(item.id).run();
    } else {
      const nextAttempt = item.attempts + 1;
      await env.DB.prepare(
        "UPDATE telegram_outbox SET state=?, lease_until_ms=0, due_ms=? WHERE id=? AND state='leased'"
      ).bind(nextAttempt >= 8 ? 'dead' : 'pending',
        nowMs + attemptDelayMs(nextAttempt), item.id).run();
    }
  }
}

async function receiveTelegram(request, env, ctx) {
  if (!(await verifyTelegramSecret(request.headers.get('x-telegram-bot-api-secret-token'),
    env.TELEGRAM_WEBHOOK_SECRET))) return json({ error: 'unauthorized' }, 401);
  if (!env.DB) return json({ error: 'not_ready' }, 503);
  const result = await parseBoundedJson(request);
  if (result.code) return json({ error: result.code === 413 ? 'too_large' : 'bad_request' }, result.code);
  const msg = toBotMessage(result.value);
  if (!msg) return json({ ok: true, ignored: true });

  // INSERT OR IGNORE means repeated update IDs cannot queue duplicate deliveries.
  // Delivery is at-least-once across a crash after Telegram accepts the send.
  await env.DB.prepare(
    "INSERT OR IGNORE INTO telegram_outbox (update_id, chat_id, body, reply_markup, state, due_ms) VALUES (?, ?, ?, ?, 'pending', ?)"
  ).bind(msg.updateId, msg.chatId, msg.text, JSON.stringify(msg.replyMarkup), Date.now()).run();

  ctx?.waitUntil?.(dispatchOutbox(env));
  if (msg.callbackId && env.BOT_TOKEN) {
    ctx?.waitUntil?.(telegramApi(env, 'answerCallbackQuery', {
      callback_query_id: msg.callbackId, cache_time: 0,
    }).catch(() => false));
  }
  return json({ ok: true });
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (request.method === 'GET' && url.pathname === '/health/live')
      return json({ status: 'alive', service: 'madar-v2' });
    if (request.method === 'GET' && url.pathname === '/health/ready') {
      const bound = Boolean(env.DB && env.BOT_TOKEN && env.TELEGRAM_WEBHOOK_SECRET);
      if (!bound) return json({ status: 'not_ready' }, 503);
      try {
        await env.DB.prepare('SELECT reply_markup FROM telegram_outbox LIMIT 1').first();
        return json({ status: 'ready' });
      } catch { return json({ status: 'not_ready' }, 503); }
    }
    if (request.method === 'POST' && url.pathname === '/telegram/webhook') {
      try { return await receiveTelegram(request, env, ctx); }
      catch { return json({ error: 'temporary_failure' }, 503); }
    }
    return json({ error: 'not_found' }, 404);
  },
  async scheduled(_event, env) { await dispatchOutbox(env); },
};
